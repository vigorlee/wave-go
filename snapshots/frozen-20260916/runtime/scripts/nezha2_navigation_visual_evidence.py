#!/usr/bin/env python3
"""Produce reproducible Nezha2 navigation and LiDAR evidence for three maps.

The locomotion layer directly loads the unmodified rl_sar_nezha2_0115
TorchScript policy.  Stair and slope commands are straight-line navigation
commands.  The obstacle case follows collision-free local waypoints.  Each
point cloud is generated by MuJoCo ray casting from the physical LiDAR body at
the same state as the rendered simulation frame.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import mujoco
import numpy as np
import torch
from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
MODEL_DIR = ROOT / "third_party/nezha2_rl_sar/rl_sar_nezha2_0115/src/rl_sar/models/nezha/robot_lab"
SCENE_DIR = ROOT / "matrix/src/robot_mujoco/zsibot_robots/nezha2"
SCENES = {
    "stairs": SCENE_DIR / "scene_terrain_stairs_clean.xml",
    "slope": SCENE_DIR / "scene_terrain_slope.xml",
    "obstacles": SCENE_DIR / "scene_terrain_obstacles.xml",
}
JOINTS = [
    f"{leg}_{joint}_joint"
    for leg in ("FL", "FR", "RL", "RR")
    for joint in ("hip", "thigh", "calf", "foot")
]
DEFAULT = np.array(
    [0.0, 0.925, -1.85, 0.0, 0.0, 0.925, -1.85, 0.0,
     0.0, -0.925, 1.85, 0.0, 0.0, -0.925, 1.85, 0.0],
    dtype=np.float32,
)
KP = np.array([150.0, 150.0, 150.0, 0.0] * 4, dtype=np.float32)
KD = np.array([4.0, 4.0, 4.0, 1.2] * 4, dtype=np.float32)
ACTION_SCALE = np.array([0.25, 0.25, 0.25, 10.0] * 4, dtype=np.float32)
TORQUE_LIMIT = np.array([150.0, 150.0, 150.0, 10.0] * 4, dtype=np.float32)
COMMAND_SCALE = np.array([2.0, 2.0, 0.25], dtype=np.float32)
LEG_MASK = np.arange(16) % 4 != 3
OBSTACLE_WAYPOINTS = np.array(
    [(-1.15, 0.45), (-1.15, 2.75), (-0.10, 3.55), (0.0, 5.70)],
    dtype=np.float64,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scenario", choices=("all", *SCENES), default="all")
    parser.add_argument("--policy", default="policy_zyl_0115_2.pt")
    parser.add_argument("--seed", type=int, default=15)
    parser.add_argument("--output-dir", type=Path, required=True)
    return parser.parse_args()


def gravity_from_quaternion(quat: np.ndarray) -> np.ndarray:
    w, x, y, z = map(float, quat)
    return np.array(
        [-2.0 * (x * z - w * y), -2.0 * (y * z + w * x), -(w * w - x * x - y * y + z * z)],
        dtype=np.float32,
    )


def yaw_from_quaternion(quat: np.ndarray) -> float:
    w, x, y, z = map(float, quat)
    return math.atan2(2.0 * (w * z + x * y), 1.0 - 2.0 * (y * y + z * z))


def wrap_angle(value: float) -> float:
    return (value + math.pi) % (2.0 * math.pi) - math.pi


def make_camera(scenario: str) -> mujoco.MjvCamera:
    camera = mujoco.MjvCamera()
    camera.type = mujoco.mjtCamera.mjCAMERA_FREE
    camera.lookat[:] = [0.0, 2.55, 0.42]
    camera.distance = 6.4 if scenario != "obstacles" else 6.8
    camera.azimuth = -112.0 if scenario != "obstacles" else -92.0
    camera.elevation = -26.0 if scenario != "obstacles" else -42.0
    return camera


def render_simulation(model: mujoco.MjModel, data: mujoco.MjData, scenario: str, destination: Path) -> None:
    model.vis.global_.offwidth = 1600
    model.vis.global_.offheight = 900
    with mujoco.Renderer(model, height=900, width=1600) as renderer:
        renderer.update_scene(data, camera=make_camera(scenario))
        Image.fromarray(renderer.render()).save(destination)


def lidar_cloud(model: mujoco.MjModel, data: mujoco.MjData) -> np.ndarray:
    lidar_body = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, "Lidar")
    base_body = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, "BASE_LINK")
    origin = np.asarray(data.xpos[lidar_body], dtype=np.float64).copy()
    azimuth = np.deg2rad(np.linspace(-180.0, 180.0, 720, endpoint=False))
    elevation = np.deg2rad(np.linspace(-26.0, 18.0, 36))
    aa, ee = np.meshgrid(azimuth, elevation)
    horizontal = np.cos(ee)
    vectors = np.column_stack(
        (horizontal.ravel() * np.cos(aa).ravel(), horizontal.ravel() * np.sin(aa).ravel(), np.sin(ee).ravel())
    ).astype(np.float64)
    nray = len(vectors)
    geomid = np.full(nray, -1, dtype=np.int32)
    distance = np.full(nray, -1.0, dtype=np.float64)
    mujoco.mj_multiRay(model, data, origin, vectors.ravel(), None, 1, base_body, geomid, distance, None, nray, 12.0)
    valid = (distance > 0.05) & (distance < 12.0) & (geomid >= 0)
    return origin[None, :] + vectors[valid] * distance[valid, None]


def plot_point_cloud(
    points_world: np.ndarray,
    robot_position: np.ndarray,
    robot_yaw: float,
    trajectory_world: np.ndarray,
    scenario: str,
    destination: Path,
) -> None:
    delta = points_world - robot_position[None, :]
    c, s = math.cos(robot_yaw), math.sin(robot_yaw)
    local = np.column_stack((c * delta[:, 0] + s * delta[:, 1], -s * delta[:, 0] + c * delta[:, 1], delta[:, 2]))
    trail = trajectory_world - robot_position[None, :2]
    trail_local = np.column_stack((c * trail[:, 0] + s * trail[:, 1], -s * trail[:, 0] + c * trail[:, 1]))

    fig = plt.figure(figsize=(10, 5.625), dpi=160, facecolor="#07131f")
    ax = fig.add_subplot(111, projection="3d", facecolor="#07131f")
    color = np.clip(local[:, 2], -0.5, 1.8)
    ax.scatter(local[:, 0], local[:, 1], local[:, 2], c=color, cmap="turbo", s=1.0, alpha=0.88, linewidths=0)
    if len(trail_local) > 1:
        ax.plot(trail_local[:, 0], trail_local[:, 1], np.full(len(trail_local), -0.02), color="#ffffff", linewidth=2.2)
    ax.scatter([0.0], [0.0], [0.0], marker="^", color="#ffdd44", s=75, label="Nezha2")
    ax.set_xlim(-1.5, 7.0)
    ax.set_ylim(-3.2, 3.2)
    ax.set_zlim(-0.6, 2.2)
    ax.set_xlabel("forward / m", color="white", labelpad=8)
    ax.set_ylabel("left / m", color="white", labelpad=8)
    ax.set_zlabel("height / m", color="white", labelpad=8)
    ax.tick_params(colors="#d7e3ef", labelsize=8)
    for axis in (ax.xaxis, ax.yaxis, ax.zaxis):
        axis.pane.set_facecolor((0.03, 0.08, 0.12, 1.0))
        axis._axinfo["grid"]["color"] = (0.35, 0.48, 0.58, 0.28)
    ax.view_init(elev=25, azim=-61)
    ax.set_title(f"{scenario}: MuJoCo ray-cast LiDAR ({len(local):,} returns)", color="white", pad=10, fontsize=12)
    fig.tight_layout(pad=0.8)
    fig.savefig(destination, facecolor=fig.get_facecolor())
    plt.close(fig)


def font(size: int) -> ImageFont.FreeTypeFont | ImageFont.ImageFont:
    candidates = [
        "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    ]
    for candidate in candidates:
        if Path(candidate).is_file():
            return ImageFont.truetype(candidate, size=size)
    return ImageFont.load_default()


def make_pair(sim_path: Path, cloud_path: Path, scenario: str, destination: Path) -> None:
    left = Image.open(sim_path).convert("RGB").resize((800, 450), Image.Resampling.LANCZOS)
    right = Image.open(cloud_path).convert("RGB").resize((800, 450), Image.Resampling.LANCZOS)
    canvas = Image.new("RGB", (1600, 510), "white")
    canvas.paste(left, (0, 60))
    canvas.paste(right, (800, 60))
    draw = ImageDraw.Draw(canvas)
    draw.rectangle((0, 0, 1599, 59), fill="#eef3f8")
    draw.line((799, 60, 799, 509), fill="#ffffff", width=3)
    label_font = font(30)
    scenario_label = {"stairs": "楼梯", "slope": "斜坡", "obstacles": "复杂路障"}[scenario]
    draw.text((400, 29), f"(a) {scenario_label} MuJoCo 仿真", anchor="mm", fill="#1c4f7c", font=label_font)
    draw.text((1200, 29), "(b) 同步 LiDAR 点云", anchor="mm", fill="#1c4f7c", font=label_font)
    canvas.save(destination)


def obstacle_command(position: np.ndarray, yaw: float, waypoint_index: int) -> tuple[np.ndarray, int]:
    index = waypoint_index
    while index < len(OBSTACLE_WAYPOINTS) - 1 and np.linalg.norm(OBSTACLE_WAYPOINTS[index] - position) < 0.42:
        index += 1
    delta = OBSTACLE_WAYPOINTS[index] - position
    distance = float(np.linalg.norm(delta))
    speed = min(0.58, max(0.22, 0.70 * distance))
    world_velocity = speed * delta / max(distance, 1e-6)
    c, s = math.cos(yaw), math.sin(yaw)
    body_vx = c * world_velocity[0] + s * world_velocity[1]
    body_vy = -s * world_velocity[0] + c * world_velocity[1]
    yaw_rate = float(np.clip(1.2 * wrap_angle(math.pi / 2.0 - yaw), -0.45, 0.45))
    return np.array([np.clip(body_vx, -0.55, 0.65), np.clip(body_vy, -0.50, 0.50), yaw_rate], dtype=np.float32), index


def run_scenario(scenario: str, policy: torch.jit.ScriptModule, seed: int, output_root: Path) -> dict[str, object]:
    torch.manual_seed(seed)
    output_dir = output_root / scenario
    output_dir.mkdir(parents=True, exist_ok=True)
    model = mujoco.MjModel.from_xml_path(str(SCENES[scenario]))
    data = mujoco.MjData(model)
    mujoco.mj_forward(model, data)
    joint_ids = [mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, name) for name in JOINTS]
    qadr = np.array([model.jnt_qposadr[joint] for joint in joint_ids])
    vadr = np.array([model.jnt_dofadr[joint] for joint in joint_ids])
    actuator_ids = [int(np.where(model.actuator_trnid[:, 0] == joint)[0][0]) for joint in joint_ids]
    gyro_id = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_SENSOR, "imu_gyro")
    gyro_adr = int(model.sensor_adr[gyro_id])
    policy_period = max(1, round(0.02 / model.opt.timestep))
    total_steps = round((18.0 if scenario != "obstacles" else 24.0) / model.opt.timestep)
    history = np.zeros((5, 57), dtype=np.float32)
    previous_action = np.zeros(16, dtype=np.float32)
    trajectory: list[tuple[float, float]] = []
    waypoint_index = 0
    capture_done = False
    collision = False

    obstacle_geom_ids = {
        geom_id for geom_id in range(model.ngeom)
        if (mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_GEOM, geom_id) or "").startswith("obstacle_")
    }

    for step in range(total_steps):
        q = np.asarray(data.qpos[qadr], dtype=np.float32)
        dq = np.asarray(data.qvel[vadr], dtype=np.float32)
        yaw = yaw_from_quaternion(np.asarray(data.qpos[3:7], dtype=np.float64))
        if scenario == "obstacles" and data.time >= 2.0:
            command, waypoint_index = obstacle_command(np.asarray(data.qpos[:2]), yaw, waypoint_index)
        else:
            command = np.array([0.0 if data.time < 2.0 else 0.62, 0.0, 0.0], dtype=np.float32)

        relative_q = q - DEFAULT
        relative_q[~LEG_MASK] = 0.0
        observation = np.concatenate(
            [
                np.asarray(data.sensordata[gyro_adr : gyro_adr + 3], dtype=np.float32) * 0.25,
                gravity_from_quaternion(np.asarray(data.qpos[3:7], dtype=np.float32)) * 0.5,
                command * COMMAND_SCALE,
                relative_q,
                dq * 0.05,
                previous_action,
            ]
        ).astype(np.float32)

        if data.time < 2.0:
            phase = np.clip(data.time / 2.0, 0.0, 1.0)
            phase = phase * phase * (3.0 - 2.0 * phase)
            target = q + phase * (DEFAULT - q)
            wheel_velocity = np.zeros(16, dtype=np.float32)
        else:
            if step % policy_period == 0:
                previous_action = policy(
                    torch.from_numpy(observation[None]), torch.from_numpy(history.reshape(1, -1))
                ).cpu().numpy()[0].astype(np.float32)
                previous_action = np.clip(previous_action, -100.0, 100.0)
                history[:-1] = history[1:]
                history[-1] = observation
            target = DEFAULT.copy()
            target[LEG_MASK] += previous_action[LEG_MASK] * ACTION_SCALE[LEG_MASK]
            wheel_velocity = np.zeros(16, dtype=np.float32)
            wheel_velocity[~LEG_MASK] = previous_action[~LEG_MASK] * ACTION_SCALE[~LEG_MASK]

        torque = np.clip(KP * (target - q) + KD * (wheel_velocity - dq), -TORQUE_LIMIT, TORQUE_LIMIT)
        data.ctrl[:] = 0.0
        for index, actuator_id in enumerate(actuator_ids):
            data.ctrl[actuator_id] = float(torque[index])
        mujoco.mj_step(model, data)

        if step % max(1, round(0.05 / model.opt.timestep)) == 0:
            trajectory.append((float(data.qpos[0]), float(data.qpos[1])))
        if scenario == "obstacles":
            for contact_index in range(data.ncon):
                contact = data.contact[contact_index]
                if contact.geom1 in obstacle_geom_ids or contact.geom2 in obstacle_geom_ids:
                    other = contact.geom2 if contact.geom1 in obstacle_geom_ids else contact.geom1
                    if other >= 0 and model.geom_bodyid[other] != 0:
                        collision = True
                        break

        capture_y = {"stairs": 2.55, "slope": 2.70, "obstacles": 2.65}[scenario]
        if not capture_done and data.qpos[1] >= capture_y:
            render_simulation(model, data, scenario, output_dir / "simulation.png")
            cloud = lidar_cloud(model, data)
            plot_point_cloud(
                cloud,
                np.asarray(data.qpos[:3], dtype=np.float64),
                yaw_from_quaternion(np.asarray(data.qpos[3:7], dtype=np.float64)),
                np.asarray(trajectory, dtype=np.float64),
                scenario,
                output_dir / "pointcloud.png",
            )
            np.save(output_dir / "pointcloud.npy", cloud)
            capture_done = True

        if data.qpos[2] < 0.14 or not np.isfinite(data.qpos).all():
            break
        goal_y = {"stairs": 4.45, "slope": 4.55, "obstacles": 5.35}[scenario]
        if data.qpos[1] >= goal_y:
            break

    if not capture_done:
        render_simulation(model, data, scenario, output_dir / "simulation.png")
        cloud = lidar_cloud(model, data)
        plot_point_cloud(
            cloud,
            np.asarray(data.qpos[:3], dtype=np.float64),
            yaw_from_quaternion(np.asarray(data.qpos[3:7], dtype=np.float64)),
            np.asarray(trajectory, dtype=np.float64),
            scenario,
            output_dir / "pointcloud.png",
        )
        np.save(output_dir / "pointcloud.npy", cloud)
    make_pair(output_dir / "simulation.png", output_dir / "pointcloud.png", scenario, output_dir / f"{scenario}_pair.png")

    goal_y = {"stairs": 4.45, "slope": 4.55, "obstacles": 5.35}[scenario]
    success = bool(data.qpos[1] >= goal_y and data.qpos[2] >= 0.25 and not collision)
    result = {
        "scenario": scenario,
        "scene": str(SCENES[scenario]),
        "policy": "policy_zyl_0115_2.pt (unmodified)",
        "success": success,
        "collision": collision,
        "time_s": float(data.time),
        "final_xyz": [float(value) for value in data.qpos[:3]],
        "waypoint_index": waypoint_index if scenario == "obstacles" else None,
        "trajectory_samples": len(trajectory),
    }
    (output_dir / "result.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result, ensure_ascii=False))
    return result


def main() -> int:
    args = parse_args()
    policy_path = MODEL_DIR / args.policy
    if args.policy.endswith("_deterministic.pt"):
        raise ValueError("This evidence run requires the unmodified stochastic policy")
    torch.set_grad_enabled(False)
    policy = torch.jit.load(str(policy_path), map_location="cpu").eval()
    scenarios = tuple(SCENES) if args.scenario == "all" else (args.scenario,)
    results = [run_scenario(name, policy, args.seed, args.output_dir) for name in scenarios]
    (args.output_dir / "summary.json").write_text(json.dumps(results, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return 0 if all(bool(result["success"]) for result in results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
